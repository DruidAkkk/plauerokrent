"""Авто-кик арендатора для PUBG Mobile (ЭКСПЕРИМЕНТАЛЬНО, по умолчанию выключено).

У PUBG Mobile вход идёт через соц-провайдера (Facebook/Google/VK/Apple/Twitter) или почту.
Единого безопасного запроса «выйти со всех устройств», как у Steam, здесь НЕТ: кикнуть арендатора
можно только разлогинив соц-сессию (как правило — сменой пароля соц-аккаунта), и у каждого
провайдера свой хрупкий флоу с антиботом и риском чекпойнта/локаута аккаунта.

Поэтому реальный «удар» по провайдеру НЕ реализован вслепую: каждый провайдер — явная точка
расширения (_kick_<provider>), которую доводят и проверяют на ПУСТОМ аккаунте, прежде чем
полагаться на неё. Пока kick() безопасно возвращает ok=False с понятной причиной, а воркер делает
штатный фолбэк (освобождает аккаунт и напоминает владельцу сменить доступ). Ничего разрушительного
по умолчанию не происходит — включается только тумблером mobile_autokick И после реализации+проверки
конкретного провайдера.
"""
from __future__ import annotations

_LABEL = {"facebook": "Facebook", "google": "Google", "twitter": "Twitter/X",
          "vk": "VK", "apple": "Apple", "email": "почта/телефон"}


async def kick(account: dict) -> dict:
    """Попытаться выкинуть арендатора с PUBG Mobile аккаунта (разлогин/смена доступа соц-входа).
    Возвращает {ok: bool, message: str}. Не бросает.

    Сейчас для всех провайдеров ok=False (механизм не доведён и не проверен) — воркер сделает
    безопасный фолбэк. Реальные флоу добавляются в _kick_<provider> ниже:
      • facebook → mbasic.facebook.com: «Выйти со всех сессий» (разлогин без смены пароля);
      • google   → accounts.google.com: выход со всех устройств (вход + возможный OTP с почты);
      • vk/apple/twitter/email → смена пароля соц-аккаунта/почты (инвалидация всех сессий).
    Каждый — только после проверки на пустом аккаунте.
    """
    lt = (account.get("login_type") or "").lower()
    label = _LABEL.get(lt, lt or "неизвестно")
    handler = _HANDLERS.get(lt)
    if handler is None:
        return {"ok": False, "message": f"авто-кик для «{label}» ещё не автоматизирован — смените доступ вручную"}
    return await handler(account)


